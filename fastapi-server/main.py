def generate_cache_key(words: List[str], context: Optional[ContextModel], endpoint: str = "predict") -> str:
    """캐시 키 생성 (words + context 기반)"""
    cache_data = {
        "words": sorted(words),  # 순서 무관하게 캐싱
        "context": {
            "previousMessages": context.previousMessages if context else []
        },
        "endpoint": endpoint
    }
    cache_str = json.dumps(cache_data, ensure_ascii=False, sort_keys=True)
    return f"aac:{endpoint}:{hashlib.md5(cache_str.encode()).hexdigest()}"

def get_from_cache(cache_key: str) -> Optional[dict]:
    """Redis에서 캐시 조회"""
    if not redis_client:
        return None
    try:
        cached = redis_client.get(cache_key)
        if cached:
            logger.info(f"✅ 캐시 HIT: {cache_key}")
            return json.loads(cached)
    except Exception as e:
        logger.warning(f"⚠️ 캐시 조회 실패: {e}")
    return None

def save_to_cache(cache_key: str, data: dict, ttl: int = 3600):
    """Redis에 캐시 저장 (기본 TTL: 1시간)"""
    if not redis_client:
        return
    try:
        redis_client.setex(cache_key, ttl, json.dumps(data, ensure_ascii=False))
        logger.info(f"✅ 캐시 저장: {cache_key}")
    except Exception as e:
        logger.warning(f"⚠️ 캐시 저장 실패: {e}")

